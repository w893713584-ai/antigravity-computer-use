function computeComponentSourceSha256(srcDir, { excludeNames = [], extraMeta = {} } = {}) {
  const hash = crypto.createHash("sha256");
  hash.update(JSON.stringify(extraMeta));
  const excluded = new Set([".DS_Store", ...excludeNames]);
  function walk(dir, relPrefix = "") {
    if (!existsSync(dir)) return;
    const entries = readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name)
    );
    for (const entry of entries) {
      if (excluded.has(entry.name)) continue;
      const abs = path.join(dir, entry.name);
      const rel = relPrefix ? `${relPrefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        hash.update(`dir:${rel}\n`);
        walk(abs, rel);
      } else if (entry.isFile()) {
        hash.update(`file:${rel}:${sha256File(abs)}\n`);
      }
    }
  }
  walk(srcDir);
  return hash.digest("hex");
}

function isGitSubpathClean(sourceRoot, relDir) {
  try {
    const out = execFileSync(
      "/usr/bin/git",
      ["-C", sourceRoot, "status", "--porcelain", "--", relDir],
      { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }
    );
    return out.trim() === "";
  } catch {
    return false;
  }
}

function extractLegacyPkgVersions(existingEntry, currentPkgVersion) {
  const versions = new Set();
  if (typeof currentPkgVersion === "string" && currentPkgVersion.trim()) {
    versions.add(currentPkgVersion.trim());
  }
  const entryVersion = typeof existingEntry?.version === "string" ? existingEntry.version.trim() : "";
  const stripped = entryVersion.replace(/\.\d+$/u, "");
  if (stripped && stripped !== entryVersion) {
    versions.add(stripped);
  }
  return [...versions];
}

async function canReuseBuiltComponent({
  role,
  appOut,
  binOut,
  zipOut,
  existingEntry,
  expectedSigningMode,
  expectedSourceSha,
  legacySourceShas = [],
  sourceRoot,
  relSrcDir,
}) {
  if (!existingEntry || !existsSync(binOut) || !existsSync(zipOut)) return false;
  if (existingEntry.signingMode !== expectedSigningMode) return false;
  if (existingEntry.binSha256 !== sha256File(binOut)) return false;
  if (existingEntry.zipSha256 !== sha256File(zipOut)) return false;
  const sourceMatches =
    existingEntry.sourceSha256 === expectedSourceSha ||
    (Array.isArray(legacySourceShas) && legacySourceShas.includes(existingEntry.sourceSha256)) ||
    (!existingEntry.sourceSha256 && isGitSubpathClean(sourceRoot, relSrcDir));
  if (!sourceMatches) return false;
  const verify = await verifyNativeAppBundle(appOut, {
    role,
    expectedBundleId: existingEntry.bundleId || null,
    requiredTeamId: existingEntry.teamId || null,
    signingMode: expectedSigningMode,
    skipSelfTest: true,
  });
  return Boolean(verify?.ok);
}

function swiftBase64Literal(filePath) {
  return readFileSync(filePath).toString("base64");
}

function generateEmbeddedAssetsSwift(scriptRunnerDir) {
  const profileB64 = swiftBase64Literal(path.join(scriptRunnerDir, "strict.sb"));
  const acornB64 = swiftBase64Literal(path.join(scriptRunnerDir, "vendor", "acorn.js"));
  const bootB64 = swiftBase64Literal(path.join(scriptRunnerDir, "bootstrap.js"));
  const outPath = path.join(scriptRunnerDir, "GeneratedEmbeddedAssets.swift");

  const content = `// Generated by scripts/build-native.mjs — DO NOT EDIT BY HAND.
import Foundation

private func decodeEmbeddedUtf8(_ b64: String) -> String {
  guard let data = Data(base64Encoded: b64),
        let str = String(data: data, encoding: .utf8)
  else {
    return ""
  }
  return str
}

enum EmbeddedScriptAssets {
  static let strictSandboxProfile: String = decodeEmbeddedUtf8("${profileB64}")
  static let acornSource: String = decodeEmbeddedUtf8("${acornB64}")
  static let bootstrapSource: String = decodeEmbeddedUtf8("${bootB64}")
}
`;
  writeFileSync(outPath, content, "utf8");
  return outPath;
}

function resolveSdkPath() {
  return execFileSync("/usr/bin/xcrun", ["--sdk", "macosx", "--show-sdk-path"], {
    encoding: "utf8",
  }).trim();
}

function compileDesktopHelperSlice({ arch, sdkPath, sourceFiles, outBin }) {
  execFileSync(
    "/usr/bin/swiftc",
    [
      "-O",
      "-target",
      `${arch}-apple-macos14.0`,
      "-sdk",
      sdkPath,
      "-framework",
      "ScreenCaptureKit",
      "-framework",
      "VideoToolbox",
      "-framework",
      "CoreMedia",
      "-framework",
      "CoreVideo",
      "-framework",
      "ImageIO",
      "-framework",
      "QuartzCore",
      "-framework",
      "Carbon",
      ...sourceFiles,
      "-o",
      outBin,
    ],
    { stdio: "inherit" }
  );
}

function compileScriptRunnerSlice({ arch, sdkPath, scriptRunnerDir, outBin, workDir }) {
  const cObj = path.join(workDir, `Seatbelt-${arch}.o`);
  execFileSync(
    "/usr/bin/clang",
    [
      "-O2",
      "-Wall",
      "-Wextra",
      "-target",
      `${arch}-apple-macos14.0`,
      "-isysroot",
      sdkPath,
      "-c",
      path.join(scriptRunnerDir, "Seatbelt.c"),
      "-o",
      cObj,
    ],
    { stdio: "inherit" }
  );

  execFileSync(
    "/usr/bin/swiftc",
    [
      "-O",
      "-target",
      `${arch}-apple-macos14.0`,
      "-sdk",
      sdkPath,
      "-import-objc-header",
      path.join(scriptRunnerDir, "Seatbelt.h"),
      "-framework",
      "JavaScriptCore",
      "-framework",
      "Foundation",
      cObj,
      path.join(scriptRunnerDir, "GeneratedEmbeddedAssets.swift"),
      path.join(scriptRunnerDir, "JscRunner.swift"),
      path.join(scriptRunnerDir, "main.swift"),
      "-o",
      outBin,
    ],
    { stdio: "inherit" }
  );
}

function buildUniversalOrHostBinary({ name, hostArch, compileSliceFn, outPath, workDir }) {
  const desiredArchs = process.env.AGY_CUA_NATIVE_ARCHS
    ? process.env.AGY_CUA_NATIVE_ARCHS.split(",").map((a) => a.trim()).filter(Boolean)
    : ["arm64", "x86_64"];

  const sliceBins = [];
  const builtArchs = [];
  for (const arch of desiredArchs) {
    const sliceOut = path.join(workDir, `${name}-${arch}`);
    try {
      compileSliceFn(arch, sliceOut);
      sliceBins.push(sliceOut);
      builtArchs.push(arch);
    } catch (err) {
      if (arch === hostArch) {
        throw err;
      }
      console.warn(`[build-native] ${name} optional slice ${arch} skipped: ${err.message}`);
    }
  }
  if (sliceBins.length === 0) {
    throw new Error(`Failed to compile ${name} for any architecture`);
  }
  mkdirSync(path.dirname(outPath), { recursive: true });
  if (sliceBins.length === 1) {
    execFileSync("/bin/cp", [sliceBins[0], outPath]);
  } else {
    execFileSync("/usr/bin/lipo", ["-create", ...sliceBins, "-output", outPath]);
  }
  chmodSync(outPath, 0o755);
  return builtArchs;
}

function renderAppInfoPlist({ templatePath, outPath, bundleId, version }) {
  let xml = readFileSync(templatePath, "utf8");
  xml = xml.replaceAll("__BUNDLE_ID__", bundleId).replaceAll("__BUNDLE_VERSION__", version);
  writeFileSync(outPath, xml, "utf8");
}

function signBundle(appPath, { identity, signingMode = null }) {
  const resolvedMode = signingMode || (identity === "-" ? "adhoc" : "developer_id");
  const baseArgs = ["--force", "--sign", identity];
  if (resolvedMode === "developer_id") {
    execFileSync(
      "/usr/bin/codesign",
      [...baseArgs, "--options", "runtime", "--timestamp", appPath],
      { stdio: "inherit" }
    );
  } else {
    // Both ad-hoc (`-`) and local self-signed certificates sign offline without `--timestamp`.
    try {
      execFileSync("/usr/bin/codesign", [...baseArgs, "--options", "runtime", appPath], {
        stdio: "pipe",
      });
    } catch {
      execFileSync("/usr/bin/codesign", [...baseArgs, appPath], { stdio: "inherit" });
    }
  }
  execFileSync("/usr/bin/codesign", ["--verify", "--deep", "--strict", appPath], {
    stdio: "inherit",
  });
}

async function runLiveJscSandboxProbe(scriptRunnerBin) {
  return new Promise((resolve, reject) => {
    const child = spawn(scriptRunnerBin, [], {
      env: {
        PATH: "/usr/bin:/bin",
        LANG: "en_US.UTF-8",
        JSC_useJIT: "false",
        JSC_useWasm: "false",
        JSC_validateOptions: "true",
      },
      stdio: ["pipe", "pipe", "pipe"],
    });
    let stdoutBuf = "";
    let stderrBuf = "";
    const outs = [];
    let settled = false;
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      try {
        child.kill("SIGKILL");
      } catch {}
      reject(new Error(`CUAScriptRunner live probe timed out (stderr=${stderrBuf})`));
    }, 8000);

    const finish = (err = null, doneMsg = null) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      try {
        child.kill("SIGKILL");
      } catch {}
      if (err) reject(err);
      else resolve({ outs, done: doneMsg });
    };

    child.stderr.on("data", (d) => {
      stderrBuf += String(d);
    });
    child.stdout.on("data", (d) => {
      stdoutBuf += String(d);
      let nl;
      while ((nl = stdoutBuf.indexOf("\n")) >= 0) {
        const line = stdoutBuf.slice(0, nl).trim();
        stdoutBuf = stdoutBuf.slice(nl + 1);
        if (!line) continue;
        let msg;
        try {
          msg = JSON.parse(line);
        } catch {
          continue;
        }
        if (msg.type === "fatal") {
          finish(new Error(`Runner fatal: ${JSON.stringify(msg)}`));
          return;
        }
        if (msg.type === "ready") {
          const probeCode = [
            "var evalBlocked = false;",
            "try { eval('1+1'); } catch (e) { evalBlocked = true; }",
            "var fnBlocked = false;",
            "try { new Function('return 1')(); } catch (e) { fnBlocked = true; }",
            "var formatted = new Intl.DateTimeFormat('zh-CN', { timeZone: 'UTC' }).format(new Date(1700000000000));",
            "nodeRepl.write(JSON.stringify({ wasmType: typeof WebAssembly, evalBlocked, fnBlocked, cjk: '中文', formatted }));",
          ].join("\n");
          child.stdin.write(
            `${JSON.stringify({
              v: 1,
              type: "run",
              runId: "build-probe-1",
              code: probeCode,
              bindings: [],
              session: {},
              requestMeta: {},
              timeoutMs: 5000,
            })}\n`
          );
        } else if (msg.type === "out") {
          outs.push(msg.item);
        } else if (msg.type === "done") {
          if (!msg.ok) {
            finish(new Error(`Runner probe done.ok=false: ${JSON.stringify(msg)}`));
          } else {
            finish(null, msg);
          }
          return;
        }
      }
    });
    child.on("error", (err) => finish(err));
    child.on("exit", (code) => {
      if (!settled) {
        finish(new Error(`CUAScriptRunner exited early (${code}): ${stderrBuf}`));
      }
    });
  });
}

export async function buildNativeBundles({
  sourceRoot = repoRoot,
  runtimeDir = NATIVE_RUNTIME_DIR,
  payloadsDir = NATIVE_PAYLOADS_DIR,
  skipLiveSelfCheck = false,
  force = false,
  codesignIdentity = null,
} = {}) {
  if (process.platform !== "darwin") {
    return { skipped: true, reason: "non_darwin" };
  }

  const hostArch = os.arch() === "x64" ? "x86_64" : os.arch();
  const {
    identity: resolvedIdentity,
    signingMode: expectedSigningMode,
    source: signingSource,
  } = resolveCodesignIdentity({ explicitIdentity: codesignIdentity });
  const isDev = expectedSigningMode !== "developer_id";
  const desiredArchs = process.env.AGY_CUA_NATIVE_ARCHS
    ? process.env.AGY_CUA_NATIVE_ARCHS.split(",").map((a) => a.trim()).filter(Boolean)
    : ["arm64", "x86_64"];
  const pkgVersion =
    JSON.parse(readFileSync(path.join(sourceRoot, "package.json"), "utf8")).version || "1.0.0";
  const bundleVersion = `${pkgVersion}.${Date.now()}`;

  const desktopHelperSrcDir = path.join(sourceRoot, "native", "DesktopHelper");
  const scriptRunnerSrcDir = path.join(sourceRoot, "native", "ScriptRunner");

  // Intentionally omit pkgVersion from sourceSha256 so JS-only version bumps reuse
  // unchanged native .app bundles and keep their CDHash / macOS TCC grants intact.
  const helperSourceSha = computeComponentSourceSha256(desktopHelperSrcDir, {
    extraMeta: { role: "desktopHelper", codesignIdentity: resolvedIdentity, desiredArchs },
  });
  const runnerSourceSha = computeComponentSourceSha256(scriptRunnerSrcDir, {
    excludeNames: ["GeneratedEmbeddedAssets.swift"],
    extraMeta: { role: "scriptRunner", codesignIdentity: resolvedIdentity, desiredArchs },
  });

  const manifestPath = path.join(payloadsDir, "manifest.json");
  let existingManifest = null;
  if (existsSync(manifestPath)) {
    try {
      existingManifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    } catch {}
  }

  const workDir = mkdtempSync(path.join(os.tmpdir(), "cua-build-native-"));
  mkdirSync(runtimeDir, { recursive: true });
  mkdirSync(payloadsDir, { recursive: true });

  const helperAppOut =
    runtimeDir === NATIVE_RUNTIME_DIR
      ? DESKTOP_HELPER_APP_PATH
      : path.join(runtimeDir, "CUADesktopHelper.app");
  const helperContents = path.join(helperAppOut, "Contents");
  const helperBinOut = path.join(helperContents, "MacOS", "CUADesktopHelper");
  const helperBundleId = getExpectedNativeBundleId("desktopHelper", { isDev });
  const helperZipName = "CUADesktopHelper.app.zip";
  const helperZipOut = path.join(payloadsDir, helperZipName);

  const runnerAppOut =
    runtimeDir === NATIVE_RUNTIME_DIR
      ? SCRIPT_RUNNER_APP_PATH
      : path.join(runtimeDir, "CUAScriptRunner.app");
  const runnerContents = path.join(runnerAppOut, "Contents");
  const runnerBinOut = path.join(runnerContents, "MacOS", "CUAScriptRunner");
  const runnerBundleId = getExpectedNativeBundleId("scriptRunner", { isDev });
  const runnerZipName = "CUAScriptRunner.app.zip";
  const runnerZipOut = path.join(payloadsDir, runnerZipName);

  try {
    console.log(
      `[build-native] Signing mode: ${expectedSigningMode} (identity=${resolvedIdentity}, source=${signingSource})`
    );
    const existingHelper = existingManifest?.components?.desktopHelper || null;
    const helperLegacySourceShas = existingHelper
      ? extractLegacyPkgVersions(existingHelper, pkgVersion).map((legacyVersion) =>
          computeComponentSourceSha256(desktopHelperSrcDir, {
            extraMeta: {
              role: "desktopHelper",
              codesignIdentity: resolvedIdentity,
              desiredArchs,
              pkgVersion: legacyVersion,
            },
          })
        )
      : [];
    const helperReused =
      !force &&
      (await canReuseBuiltComponent({
        role: "desktopHelper",
        appOut: helperAppOut,
        binOut: helperBinOut,
        zipOut: helperZipOut,
        existingEntry: existingHelper,
        expectedSigningMode,
        expectedSourceSha: helperSourceSha,
        legacySourceShas: helperLegacySourceShas,
        sourceRoot,
        relSrcDir: "native/DesktopHelper",
      }));

    const existingRunner = existingManifest?.components?.scriptRunner || null;
    const runnerLegacySourceShas = existingRunner
      ? extractLegacyPkgVersions(existingRunner, pkgVersion).map((legacyVersion) =>
          computeComponentSourceSha256(scriptRunnerSrcDir, {
            excludeNames: ["GeneratedEmbeddedAssets.swift"],
            extraMeta: {
              role: "scriptRunner",
              codesignIdentity: resolvedIdentity,
              desiredArchs,
              pkgVersion: legacyVersion,
            },
          })
        )
      : [];
    const runnerReused =
      !force &&
      (await canReuseBuiltComponent({
        role: "scriptRunner",
        appOut: runnerAppOut,
        binOut: runnerBinOut,
        zipOut: runnerZipOut,
        existingEntry: existingRunner,
        expectedSigningMode,
        expectedSourceSha: runnerSourceSha,
        legacySourceShas: runnerLegacySourceShas,
        sourceRoot,
        relSrcDir: "native/ScriptRunner",
      }));

    let sdkPath = null;
    if (!helperReused || !runnerReused) {
      sdkPath = resolveSdkPath();
    }

    let helperEntry;
    if (helperReused) {
      helperEntry = {
        ...existingHelper,
        sourceSha256: helperSourceSha,
      };
      console.log(
        `[build-native] Reusing unchanged CUADesktopHelper.app (${existingHelper.bundleId}, preserving CDHash/TCC)`
      );
    } else {
      rmSync(helperAppOut, { recursive: true, force: true });
      mkdirSync(path.join(helperContents, "MacOS"), { recursive: true });

      const helperSwiftFiles = readdirSync(desktopHelperSrcDir)
        .filter((f) => f.endsWith(".swift"))
        .sort()
        .map((f) => path.join(desktopHelperSrcDir, f));

      const helperArchs = buildUniversalOrHostBinary({
        name: "CUADesktopHelper",
        hostArch,
        outPath: helperBinOut,
        workDir,
        compileSliceFn: (arch, outBin) =>
          compileDesktopHelperSlice({ arch, sdkPath, sourceFiles: helperSwiftFiles, outBin }),
      });
      renderAppInfoPlist({
        templatePath: path.join(desktopHelperSrcDir, "Info.plist"),
        outPath: path.join(helperContents, "Info.plist"),
        bundleId: helperBundleId,
        version: bundleVersion,
      });
      signBundle(helperAppOut, { identity: resolvedIdentity, signingMode: expectedSigningMode });
      rmSync(helperZipOut, { force: true });
      await execFileAsync(
        "/usr/bin/ditto",
        ["-c", "-k", "--sequesterRsrc", "--keepParent", helperAppOut, helperZipOut],
        { timeout: 15_000 }
      );
      const helperSignInfo = await inspectCodesign(helperAppOut);
      helperEntry = {
        bundleId: helperBundleId,
        version: bundleVersion,
        teamId: helperSignInfo.teamId || null,
        authority: helperSignInfo.authorities?.[0] || null,
        cdhash: helperSignInfo.cdhash || null,
        signingMode: expectedSigningMode,
        archs: helperArchs,
        binSha256: sha256File(helperBinOut),
        zipFile: helperZipName,
        zipSha256: sha256File(helperZipOut),
        sourceSha256: helperSourceSha,
      };
    }

    let runnerEntry;
    if (runnerReused) {
      runnerEntry = {
        ...existingRunner,
        sourceSha256: runnerSourceSha,
      };
      console.log(`[build-native] Reusing unchanged CUAScriptRunner.app (${existingRunner.bundleId})`);
    } else {
      generateEmbeddedAssetsSwift(scriptRunnerSrcDir);
      rmSync(runnerAppOut, { recursive: true, force: true });
      mkdirSync(path.join(runnerContents, "MacOS"), { recursive: true });

      const runnerArchs = buildUniversalOrHostBinary({
        name: "CUAScriptRunner",
        hostArch,
        outPath: runnerBinOut,
        workDir,
        compileSliceFn: (arch, outBin) =>
          compileScriptRunnerSlice({ arch, sdkPath, scriptRunnerDir: scriptRunnerSrcDir, outBin, workDir }),
      });
      renderAppInfoPlist({
        templatePath: path.join(scriptRunnerSrcDir, "Info.plist"),
        outPath: path.join(runnerContents, "Info.plist"),
        bundleId: runnerBundleId,
        version: bundleVersion,
      });
      signBundle(runnerAppOut, { identity: resolvedIdentity, signingMode: expectedSigningMode });
      rmSync(runnerZipOut, { force: true });
      await execFileAsync(
        "/usr/bin/ditto",
        ["-c", "-k", "--sequesterRsrc", "--keepParent", runnerAppOut, runnerZipOut],
        { timeout: 15_000 }
      );
      const runnerSignInfo = await inspectCodesign(runnerAppOut);
      runnerEntry = {
        bundleId: runnerBundleId,
        version: bundleVersion,
        teamId: runnerSignInfo.teamId || null,
        authority: runnerSignInfo.authorities?.[0] || null,
        cdhash: runnerSignInfo.cdhash || null,
        signingMode: expectedSigningMode,
        archs: runnerArchs,
        binSha256: sha256File(runnerBinOut),
        zipFile: runnerZipName,
        zipSha256: sha256File(runnerZipOut),
        sourceSha256: runnerSourceSha,
      };
    }

    if (!skipLiveSelfCheck) {
      const denialRes = await runScriptRunnerDenialSelfTest(runnerBinOut);
      if (!denialRes.ok) {
        throw new Error(
          `CUAScriptRunner Seatbelt denial self-test failed: ${JSON.stringify(denialRes)}`
        );
      }
      const jscRes = await runLiveJscSandboxProbe(runnerBinOut);
      const parsedOut = JSON.parse(jscRes.outs?.[0]?.text || "{}");
      if (
        parsedOut.wasmType !== "undefined" ||
        parsedOut.evalBlocked !== true ||
        parsedOut.fnBlocked !== true ||
        parsedOut.cjk !== "中文"
      ) {
        throw new Error(`CUAScriptRunner live JSC self-check mismatch: ${JSON.stringify(parsedOut)}`);
      }
      const encSelfTest = await runDesktopHelperEncoderSelfTest(helperBinOut);
      if (!encSelfTest.ok) {
        throw new Error(
          `CUADesktopHelper hardware H.264 encoder self-test failed: ${JSON.stringify(encSelfTest)}`
        );
      }
      console.log(
        `[build-native] Seatbelt + JSC self-checks OK (${JSON.stringify(denialRes.report)}, ${JSON.stringify(parsedOut)})`
      );
      console.log(`[build-native] H.264 encoder self-test OK (${JSON.stringify(encSelfTest)})`);
    }

    const manifest = {
      version: EXPECTED_NATIVE_MANIFEST_VERSION,
      builtAt: new Date().toISOString(),
      signingMode: expectedSigningMode,
      components: {
        desktopHelper: helperEntry,
        scriptRunner: runnerEntry,
      },
    };
    writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
    return {
      skipped: false,
      reused: { desktopHelper: helperReused, scriptRunner: runnerReused },
      manifestPath,
      manifest,
    };
  } finally {
    rmSync(workDir, { recursive: true, force: true });
  }
}

function parseBuildNativeCliArgs(argv) {
  const opts = {
    ifMissing: false,
    force: false,
    skipLiveSelfCheck: false,
    codesignIdentity: null,
    runtimeDir: NATIVE_RUNTIME_DIR,
    payloadsDir: NATIVE_PAYLOADS_DIR,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--if-missing") opts.ifMissing = true;
    else if (arg === "--force") opts.force = true;
    else if (arg === "--skip-self-check") opts.skipLiveSelfCheck = true;
    else if (arg === "--identity" && i + 1 < argv.length) opts.codesignIdentity = argv[++i];
    else if (arg === "--runtime-dir" && i + 1 < argv.length) opts.runtimeDir = path.resolve(argv[++i]);
    else if (arg === "--payloads-dir" && i + 1 < argv.length) opts.payloadsDir = path.resolve(argv[++i]);
  }
  return opts;
}

if (isMainModule(import.meta.url)) {
  const cli = parseBuildNativeCliArgs(process.argv.slice(2));
  if (cli.ifMissing && !cli.force) {
    if (process.platform !== "darwin") {
      process.exit(0);
    }
    const helperBinCheck =
      cli.runtimeDir === NATIVE_RUNTIME_DIR
        ? DESKTOP_HELPER_BIN_PATH
        : path.join(cli.runtimeDir, "CUADesktopHelper.app", "Contents", "MacOS", "CUADesktopHelper");
    const runnerBinCheck =
      cli.runtimeDir === NATIVE_RUNTIME_DIR
        ? SCRIPT_RUNNER_BIN_PATH
        : path.join(cli.runtimeDir, "CUAScriptRunner.app", "Contents", "MacOS", "CUAScriptRunner");
    if (
      existsSync(helperBinCheck) &&
      existsSync(runnerBinCheck) &&
      existsSync(path.join(cli.payloadsDir, "manifest.json"))
    ) {
      process.exit(0);
    }
  }
  buildNativeBundles({
    runtimeDir: cli.runtimeDir,
    payloadsDir: cli.payloadsDir,
    skipLiveSelfCheck: cli.skipLiveSelfCheck,
    force: cli.force,
    codesignIdentity: cli.codesignIdentity,
  })
    .then((res) => {
      if (res.skipped) {
        console.log(`[build-native] skipped (${res.reason})`);
      } else {
        console.log(`[build-native] Built & verified native payloads -> ${res.manifestPath}`);
      }
    })
    .catch((err) => {
      console.error("[build-native] FAILED:", err);
      process.exit(1);
    });
}
